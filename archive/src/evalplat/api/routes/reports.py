"""报告与导出 API 路由。"""

import uuid
import re
from datetime import datetime
from pathlib import Path

from fastapi import APIRouter, Depends, Header, Query
from fastapi.responses import FileResponse
from sqlalchemy import select
from sqlalchemy.orm import Session

from evalplat.api.deps import get_db
from evalplat.services import report_service
from evalplat.config import get_settings
from evalplat.api.deps import PaginationParams
from evalplat.schemas.report import ReportGenerateResponse, ReportList, ReportRead
from evalplat.services.history_cleanup_service import report_file_cleanup_in_progress
from evalplat.services.history_cleanup_service import report_file_registered
from evalplat.models.run import Run
from evalplat.models.report import Report
from evalplat.services.security_service import redact_sensitive_text, redact_sensitive_value

router = APIRouter(tags=["报告与导出"])


def _report_read(report: Report) -> ReportRead:
    """Serialize report metadata without leaking user-supplied secrets."""

    payload = ReportRead.model_validate(report).model_dump()
    payload["snapshot"] = redact_sensitive_value(payload.get("snapshot"))
    payload["error"] = redact_sensitive_text(payload.get("error")) or None
    return ReportRead(**payload)


@router.post("/tasks/{task_id}/report", response_model=ReportGenerateResponse, status_code=200)
def generate_report(
    task_id: uuid.UUID,
    idempotency_key: str | None = Header(default=None, alias="Idempotency-Key"),
    db: Session = Depends(get_db),
):
    """为指定任务生成静态摘要报告。"""
    return ReportGenerateResponse.model_validate(
        report_service.generate_report(db, task_id, idempotency_key=idempotency_key)
    )


@router.get("/tasks/{task_id}/reports", response_model=ReportList)
def list_reports(
    task_id: uuid.UUID,
    pagination: PaginationParams = Depends(),
    status: str | None = Query(None),
    created_from: datetime | None = Query(None),
    created_to: datetime | None = Query(None),
    db: Session = Depends(get_db),
):
    """查询任务的全部不可变报告版本。"""

    items, total = report_service.list_reports(
        db,
        task_id,
        skip=pagination.skip,
        limit=pagination.limit,
        status_filter=status,
        created_from=created_from,
        created_to=created_to,
    )
    return ReportList(items=[_report_read(item) for item in items], total=total)


@router.get("/reports", response_model=ReportList)
def list_all_reports(
    pagination: PaginationParams = Depends(),
    task_id: uuid.UUID | None = Query(None),
    supplier_id: uuid.UUID | None = Query(None),
    status: str | None = Query(None),
    created_from: datetime | None = Query(None),
    created_to: datetime | None = Query(None),
    db: Session = Depends(get_db),
):
    """跨任务查询报告，支持任务、供应商、状态和日期筛选。"""
    items, total = report_service.list_reports(
        db,
        task_id=task_id,
        supplier_id=supplier_id,
        status_filter=status,
        created_from=created_from,
        created_to=created_to,
        skip=pagination.skip,
        limit=pagination.limit,
    )
    return ReportList(items=[_report_read(item) for item in items], total=total)


@router.get("/reports/files/{filename}")
def download_report(filename: str, db: Session = Depends(get_db)):
    """下载报告目录中的已生成文件，阻止目录穿越。"""
    root = Path(get_settings().report_dir).expanduser().resolve()
    candidate = (root / filename).resolve()
    if candidate.parent != root or not candidate.is_file():
        from evalplat.core.errors import NotFoundError
        raise NotFoundError("报告文件不存在")
    # Static report pages must be registered by a completed Report.  CSV/JSON
    # exports intentionally remain in the same operational directory for
    # backwards-compatible URLs, but are allowed only for the exact run-based
    # filenames generated by this service and while that Run still exists.
    export_match = re.fullmatch(r"run-([0-9a-fA-F-]{36})\.(csv|json)", filename)
    registered = report_file_registered(db, candidate)
    if not registered and export_match:
        try:
            run_id = uuid.UUID(export_match.group(1))
        except ValueError:
            run_id = None
        registered = run_id is not None and db.scalar(select(Run.id).where(Run.id == run_id)) is not None
    if not registered:
        from evalplat.core.errors import NotFoundError
        raise NotFoundError("报告文件不存在")
    if report_file_cleanup_in_progress(db, candidate):
        from evalplat.core.errors import ConflictError
        raise ConflictError("报告所属任务正在清理，暂不能下载")
    return FileResponse(candidate)


@router.get("/reports/{report_id}", response_model=ReportRead)
def get_report(report_id: uuid.UUID, db: Session = Depends(get_db)):
    return _report_read(report_service.get_report(db, report_id))


